// Скользящее окно. Оба указателя идут вправо. Окно расширяется и сужается.

// ⱥ  b  c  d  e
//    ↑        ↑
//    L        R

// Подстроки, подмассивы.

// Пример.
// Максимальная сумма подмассива длины k.

function maxSum(nums, k) {
  // nums - массив, k - количество элементов подмножества
  let windowSum = 0; // хранит текущую сумму элементов в "окне" (подмножестве) длиной k
  // Вычисление суммы первого окна. В цикле for проходим по первым k элементам массива
  // (индексы от 0 до k - 1) и суммируем их значения. Например, если nums = [1, 2, 3, 4, 5]
  // и k = 3, то после этого цикла windowSum будет равен 1 + 2 + 3 = 6. Это сумма первого окна [1, 2, 3].
  for (let i = 0; i < k; i++) {
    windowSum += nums[i];
  }

  // Инициализация результата
  // Переменная result будет хранить максимальное значение суммы, найденное за все время
  // работы алгоритма. Инициализируем ее значением первой вычисленной суммы (на данный момент
  // это единственная известная нам сумма окна).
  let result = windowSum;

  // Сдвиг окна и поиск максимума
  // Это основной цикл алгоритма. Он начинается с индекса k, то есть с элемента, который идёт сразу за первым окном.
  // Как работает сдвиг окна:
  // Представьте окно из k элементов. Чтобы сдвинуть его на одну позицию вправо, нам нужно:

  // Убрать из суммы самый левый элемент предыдущего окна.
  // Добавить в сумму новый элемент, который оказался справа.
  // В коде это делается одной строкой: windowSum += nums[i] - nums[i - k].
  // nums[i] — это новый элемент, который мы добавляем в окно.
  // nums[i - k] — это элемент, который находился в начале предыдущего окна и теперь из него выходит.
  // Цикл продолжается до тех пор, пока окно не дойдёт до конца массива.
  for (let i = k; i < nums.length; i++) {
    windowSum = windowSum + nums[i] - nums[i - k];
    result = Math.max(result, windowSum);
  }

  return result;
}
