// Пирамида. Спросите n. Выведите центрированную пирамиду из * высотой n строк.
// Строка i содержит (2i−1) звёздочек, выровненных по центру.

let n = Number(prompt("Число:")); // n = 4

for (let i = 1; i <= n; i++) {
  // i увеличивается на 1 на каждой итерации (до 4 включительно).
  // Всего 4 итерации (строки пирамиды).
  let spaces = " ".repeat(n - i); // На каждой строке (n - i) = 3 (всегда!).
  let stars = "* ".repeat(2 * i - 1);
  // Для i = 1: 2*1-1 = 1 → "* " (звезда с пробелом)
  // Для i = 2: 2*2-1 = 3 → "* * * "
  // Для i = 3: 2*3-1 = 5 → "* * * * * "
  // Для i = 4: 2*4-1 = 7 → "* * * * * * * "

  console.log(spaces + stars); // Склеивает пробелы и звёздочки, выводит в консоль.
}


// Строка 1:   *      ← 3 пробела, 1 звезда
// Строка 2:  ***     ← 2 пробела, 3 звезды
// Строка 3: *****    ← 1 пробел,  5 звёзд
// Строка 4:*******   ← 0 пробелов, 7 звёзд