// Считаем пары.,

function countDivisors(n) {
  // Проверка на корректность входных данных
  if (n <= 0) {
    return 0;
  }

  let count = 0;
  // Перебираем потенциальные делители от 1 до квадратного корня из n
  for (let i = 1; i <= Math.floor(Math.sqrt(n)); i++) {
    // √12 = 3
    if (n % i === 0) {
      // Два уникальных делителя (например, 2 и 6 для числа 12)
      if (i !== n / i) {
        // Проверка: 2 !== 12 / 2 → 2 != 6 → условие истинно. Добавляем += 2 к count
        count += 2; // Почему +2 ? Потому что мы одновременно нашли два делителя: 2 и 6.
        // Если бы просто прибавляли по одному за каждую итерацию, нам пришлось бы перебирать
        // числа до самого 12. Этот метод позволяет найти пару делителей за один шаг.
      } else {
        // Если делитель является квадратным корнем из n (например, 4 для числа 16),
        // и его "пара" - это он сам.
        // i равно n / i.
        count += 1; // Почему +1 ? Потому что корень из 16 (число 4) является только одним
        // уникальным делителем. Если бы мы прибавили +2, мы бы посчитали число 4 дважды, а это ошибка.
      }
    }
  }
  return count;
}

console.log(countDivisors(12)); // Выведет: 6

