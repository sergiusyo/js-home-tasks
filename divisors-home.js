// Считаем пары.
function countDivisors(n) {
  // Проверка на корректность входных данных
  if (n <= 0) {
    return 0;
  }

  let count = 0;
  // Перебираем потенциальные делители от 1 до квадратного корня из n. Это верхняя граница для цикла
  for (let d = 1; d <= Math.floor(Math.sqrt(n)); d++) {
    // √12 = 3
    if (n % d === 0) {
      // Два уникальных делителя (например, 2 и 6 для числа 12)
      if (d !== n / d) { // для числа 12 и делителя 2 парный ему делитель 12/2 = 6. Они различны.
        // Добавляем += 2 к count
        count += 2; // Почему +2 ? Потому что мы одновременно нашли два делителя: 2 и 6.
        // Если бы просто прибавляли по одному за каждую итерацию, нам пришлось бы перебирать
        // числа до самого 12. Этот метод позволяет найти пару делителей за один шаг.
      } else {
        // Если делитель является квадратным корнем из n (например, 4 для числа 16),
        // и его "пара" - это он сам (d === n / d).
        count += 1; // Почему +1 ? Потому что корень из 16 (число 4) является только одним
        // уникальным делителем. Если бы мы прибавили +2, мы бы посчитали число 4 дважды, а это ошибка.
      }
    }
  }
  return count;
}

// console.log(countDivisors(12)); // Выведет: 6

// Сумма всех делителей.
function sumDivisors(n) {
  // Находим целую часть квадратного корня из n (верхняя граница для цикла)
  const sqrtN = Math.floor(Math.sqrt(n));
  let total = 0;

  // Перебираем потенциальные делители от 1 до sqrt(n)
  for (let d = 1; d <= sqrtN; d++) {
    if (n % d === 0) {
      // Если d - делитель, то n / d тоже делитель.
      total += d + (d !== n / d ? n / d : 0); // Если d - делитель, то его значение сразу
      // добавляется к общей сумме (total)
      // (d !== n / d ? n / d : 0); - тернарный оператор, обрабатывающий парный делитель.
      // Если d !== n / d, то к сумме прибавляется парный делитель (в большинстве случаев).
      // Если d равно n / d, то n является полным квадратом и мы нашли корень из числа.
      // В этом случае, чтобы не посчитать один и тот же делитель дважды, добавляется 0.
    }
  }
  return total;
}

