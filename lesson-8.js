// Сумма цифр
let n = prompt("Число: 1234");
let sum = 0;
for (let i = 0; i < n.length; i++) {
  // Начинаем с первого символа строки
  // Продолжаем, пока не переберём все символы
  // Переходим к следующему символу
  sum += Number(n[i]);
  // n[i] — обращение к i-му символу строки (например, "1234"[0] → "1")
  // Number(...) — преобразует символ-цифру в число (например, "1" → 1)
  // sum += ... — добавляет цифру к общей сумме
}

console.log("Сумма цифр:", sum);
