// Оптимизация до O(√n). Делители всегда парны → достаточно найти только меньшие из пар.
// Если d × d == n, то d и n/d — это один и тот же делитель. Добавляем его один раз.
// n = 36: 6 × 6 = 36
// d = 6 добавляем один раз, не два

function getDivisors(n) {
  // Проверка на "положительность" числа
  if (n <= 0) {
    throw new Error("Число должно быть положительным");
  }

  const small = []; // массив для хранения делителей, которые меньше или равны √n
  const large = []; // массив для хранения делителей, которые больше или равны √n

  const sqrtN = Math.floor(Math.sqrt(n)); // вычисляется целочисленное значение
  // квадратного корня из n и сохраняется в переменную sqrtN

  for (let d = 1; d <= sqrtN; d++) {
    if (n % d === 0) {
      // Если остаток от деления равен 0, значит d - делитель числа n
      small.push(d);

      if (d !== n / d) {
        // Вычисляется парный делитель n / d. Если он не равен самому d (это происходит
        // только когда n является полным квадратом, например для 36 и d = 6), то парный
        // делитель добавляется в массив large. Это гарантирует, что квадратный корень
        // из числа не будет добавлен дважды.
        large.push(n / d);
      }
    }
  }

  return small.concat(large.reverse());
}

