// Создать функцию once, которая гарантирует, что переданная функция будет вызвана только один раз.

var once = function (fn) {
  let called = false; // флаг, была ли уже вызвана функция
  let result; // сохраняет результат первого вызова

  // Использует оператор rest (...args) для сбора всех аргументов
  // Проверяет флаг called
  // При первом вызове:
  // Устанавливает called = true
  // Вызывает fn с переданными аргументами
  // Сохраняет результат в result
  // Возвращает результат
  // При последующих вызовах:
  // Просто возвращает undefined

  return function (...args) {
    if (!called) {
      called = true;
      result = fn(...args);
      return result;
    }
    return undefined;
  };
};

// Запоминает, была ли вызвана исходная функция
// При первом вызове:
// Вызывает переданную функцию fn с переданными аргументами
// Сохраняет результат
// Возвращает результат
// При последующих вызовах:
// Не вызывает fn
// Возвращает undefined

