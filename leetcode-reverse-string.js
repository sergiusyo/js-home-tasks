// Напишите функцию, которая преобразует строку в обратном порядке. Входная строка задается в виде массива символов s.
var reverseString = function (s) {
  let left = 0; // указатель на начало массива
  let right = s.length - 1; // указатель на конец массива

  while (left < right) {
    // пока указатели не встретятся
    // Обмен значений через деструктуризацию (без временной переменной)
    [s[left], s[right]] = [s[right], s[left]];

    left++; // двигаем левый указатель вправо
    right--; // двигаем правый указатель влево
  }
  // Ничего не возвращаем (undefined)
};
